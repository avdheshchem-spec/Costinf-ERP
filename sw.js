// Minimal "app shell" service worker. This ERP already keeps all its real data in the
// browser (localStorage) rather than on a server, so there's no API traffic to worry
// about — the only thing worth caching is the app shell itself (index.html + icons),
// so the app still opens with no signal at all, e.g. in a warehouse or on a flight.
const CACHE_NAME = 'costing-erp-shell-v1';
const SHELL_FILES = [
  './',
  './index.html',
  './manifest.json',
  './icon-192.png',
  './icon-512.png',
  './icon-512-maskable.png'
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(SHELL_FILES)).then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((names) =>
      Promise.all(names.filter((n) => n !== CACHE_NAME).map((n) => caches.delete(n)))
    ).then(() => self.clients.claim())
  );
});

// Cache-first for the shell, falling back to network (and updating the cache) —
// this app rarely changes shape day-to-day, so a slightly stale shell is fine and
// keeps things instant; a hard refresh after an update always picks up the latest.
self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET') return;
  event.respondWith(
    caches.match(event.request).then((cached) => {
      if (cached) return cached;
      return fetch(event.request).then((response) => {
        if (response && response.status === 200) {
          const copy = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(event.request, copy));
        }
        return response;
      }).catch(() => cached);
    })
  );
});
